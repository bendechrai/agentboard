/**
 * The lease fixture board (add-claim-leases task 3.2): a fixed set of event
 * files in `fixtures/lease-board/events/`, read at the fixed clock in
 * `golden/leases/clock.json` (2026-10-26T12:00:00.000Z), with one ticket in
 * each lease situation the goldens cover. Every ticket is an ad hoc
 * `merge lock` created by `orchestrator` an hour before the clock:
 *
 * - `free`: never claimed.
 * - `grace`: claimed by `merger-1` 30 s ago with `--ttl 30m`, not renewed
 *   (grace lease, 90 s left).
 * - `confirmed`: claimed by `impl-1` and renewed 5 minutes ago for 30m.
 * - `expired`: claimed by `impl-2` 140 s ago with `--ttl 30m`, not renewed
 *   (its grace ended 20 s ago; claimable in 40 s).
 * - `claimable`: claimed and renewed by `impl-3` for 10m, lapsed 5
 *   minutes ago.
 * - `queued`: held by `merger-1` (renewed for 30m 100 s ago) with
 *   `merger-2`, `merger-3` and `merger-4` queued in that order.
 * - `granted`: held without a lease by `merger-5`, `merger-6` queued,
 *   released 60 s ago, granted to `merger-6` (the grant event is part of
 *   the fixture, derived with `dueGrant`), not accepted yet.
 * - `takenOver`: `impl-4`'s grace lease taken over by `impl-5` (`--ttl
 *   1h`), who renewed.
 * - `forced`: `merger-7`'s plain claim force-released by `orchestrator`
 *   with reason `merger-7 crashed`.
 *
 * The files and the goldens were generated by a throwaway program from
 * the spec formulas and the stub contracts, using only the events layer
 * (fold, `dueGrant`, canonical encoding); the reviewer recomputes them
 * the same way. No grant is due at the clock that the fixture does not
 * hold, so reading the board at the clock writes nothing.
 */

import { cpSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { project } from './cli-helpers.js';

const HERE = dirname(fileURLToPath(import.meta.url));

/** The fixture's event files. */
export const LEASE_EVENTS = join(HERE, 'fixtures', 'lease-board', 'events');

/** The golden directory. */
export const LEASE_GOLDEN = join(HERE, 'golden', 'leases');

/** The ticket names of the fixture, as in `clock.json`. */
export type LeaseTicket =
  | 'free'
  | 'grace'
  | 'confirmed'
  | 'expired'
  | 'claimable'
  | 'queued'
  | 'granted'
  | 'takenOver'
  | 'forced';

interface Clock {
  now: number;
  iso: string;
  ids: Record<LeaseTicket, string>;
}

const clock = JSON.parse(readFileSync(join(LEASE_GOLDEN, 'clock.json'), 'utf8')) as Clock;

/** The fixed clock the goldens are read at. */
export const LEASE_NOW = clock.now;

/** The ticket ids of the fixture. */
export const LEASE_ID: Readonly<Record<LeaseTicket, string>> = clock.ids;

/** Every ticket name, in id order. */
export const LEASE_TICKETS = (Object.keys(clock.ids) as LeaseTicket[]).sort((a, b) =>
  clock.ids[a] < clock.ids[b] ? -1 : 1,
);

/** A golden file's text. */
export function golden(name: string): string {
  return readFileSync(join(LEASE_GOLDEN, name), 'utf8');
}

/** A golden JSON file, parsed. */
export function goldenJson(name: string): unknown {
  return JSON.parse(golden(name)) as unknown;
}

/** A project whose board holds a copy of the fixture's event files. */
export function leaseFixture(): { root: string; boardDir: string; eventsDir: string } {
  const { root, boardDir } = project();
  const eventsDir = join(boardDir, 'events');
  cpSync(LEASE_EVENTS, eventsDir, { recursive: true });
  return { root, boardDir, eventsDir };
}

/** The sorted file names of the fixture's events. */
export function fixtureNames(): string[] {
  return readdirSync(LEASE_EVENTS).sort();
}
